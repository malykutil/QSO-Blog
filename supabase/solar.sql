create or replace function public.touch_solar_relay_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = timezone('utc', now()); return new; end; $$;
drop trigger if exists solar_relay_updated_at on public.solar_relay_states;
create trigger solar_relay_updated_at before update on public.solar_relay_states
for each row execute function public.touch_solar_relay_updated_at();

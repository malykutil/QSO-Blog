create table if not exists public.solar_relay_states (
  relay text primary key check (relay in ('solar1', 'solar2', 'battery', 'bufik', 'fan12v', 'fan24v')),
  is_on boolean not null default false,
  updated_at timestamptz not null default timezone('utc', now())
);

insert into public.solar_relay_states (relay) values
  ('solar1'), ('solar2'), ('battery'), ('bufik'), ('fan12v'), ('fan24v')
on conflict (relay) do nothing;

alter table public.solar_telemetry enable row level security;
alter table public.solar_relay_states enable row level security;

